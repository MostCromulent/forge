package forge.web.lobby;

import forge.StaticData;
import forge.card.CardEdition;
import forge.card.CardRarity;
import forge.deck.DeckFormat;
import forge.deck.FormatChoices;
import forge.game.GameFormat;
import forge.game.GameType;
import forge.util.Localizer;
import forge.web.protocol.ToBrowser.Format;
import forge.web.protocol.ToBrowser.FormatGroup;
import org.apache.commons.lang3.Range;

import java.util.ArrayList;
import java.util.List;
import java.util.stream.Stream;

/** What the lobby tells a browser about each format, casual variant and card pool. None of it depends on the table. */
public final class LobbyFormats {
    /** The formats on offer, in desktop's order. Every format except Constructed is a variant. Constructed means no variant. */
    static final List<GameType> FORMATS = Stream.concat(Stream.of(GameType.Constructed), FormatChoices.FORMAT_GAME_TYPES.stream()).toList();

    /** The casual variants. Each one can be added to any format that the engine allows it with. */
    static final List<GameType> VARIANTS = FormatChoices.STACKED_GAME_TYPES;

    /** The description uses the web's own wording, because the engine's older text still calls a commander a "General". */
    static Format explained(final GameType type) {
        final Localizer text = Localizer.getInstance();
        // Grouped the way Wizards groups formats: Constructed formats, the Commander family, and the rest
        final FormatGroup group = type == GameType.Constructed ? FormatGroup.Constructed
                : type.getDeckFormat().hasCommander() ? FormatGroup.Commander : FormatGroup.Other;
        final Integer cards = deckCards(type);
        final boolean atLeast = cards != null && (type.getDeckFormat().getMainRange().getMaximum() == Integer.MAX_VALUE
                || type.getDeckFormat().getMaxCardCopies() != 1);
        final String deckFact = cards == null ? text.getMessage("lblWebFactDeckNone")
                : text.getMessage(atLeast ? "lblWebFactDeckAtLeast" : "lblWebFactDeckSingleton", cards);
        return new Format(type.name(), type.toString(), group, text.getMessage("lblWebDesc" + type.name()),
                List.of(deckFact, lifeFact(type)), text.getMessage("lblWebPlay" + type.name()), cards, atLeast);
    }

    /** The deck size a player builds to, counting the cards that start in the command zone, or null when the deck is dealt. */
    private static Integer deckCards(final GameType type) {
        if (type.isAutoGenerated()) {
            return null;
        }
        final DeckFormat deck = type.getDeckFormat();
        final Range<Integer> main = deck.getMainRange();
        if (main.getMaximum() == Integer.MAX_VALUE) {
            return main.getMinimum();
        }
        // Oathbreaker's command zone holds the oathbreaker and its signature spell
        return main.getMaximum() + (type == GameType.Oathbreaker ? 2 : deck.hasCommander() ? 1 : 0);
    }

    /** Starting life, as RegisteredPlayer.forVariants sets it: 20, plus each format's bonus. */
    private static String lifeFact(final GameType type) {
        final Localizer text = Localizer.getInstance();
        return switch (type) {
            case Commander -> text.getMessage("lblWebFactLife", 40);
            case TinyLeaders -> text.getMessage("lblWebFactLife", 25);
            case MomirBasic, MoJhoSto -> text.getMessage("lblWebFactLifeAvatar");
            case Brawl -> text.getMessage("lblWebFactLifeByPlayers", 25, 30);
            default -> text.getMessage("lblWebFactLife", 20);
        };
    }

    /** A casual variant and what the lobby says about it, in the same shape as a format. */
    static Format explainedVariant(final GameType type) {
        final Localizer text = Localizer.getInstance();
        final List<String> facts = switch (type) {
            case Planechase -> List.of(text.getMessage("lblWebFactPlanes"));
            case Vanguard -> List.of(text.getMessage("lblWebFactOneAvatar"), text.getMessage("lblWebFactAvatarChanges"));
            case Archenemy -> List.of(text.getMessage("lblWebFactSchemesArchenemy"), text.getMessage("lblWebFactArchenemyLife"));
            case ArchenemyRumble -> List.of(text.getMessage("lblWebFactSchemesEveryone"), text.getMessage("lblWebFactEveryoneLife"));
            case TwoHeadedGiant -> List.of(text.getMessage("lblWebFactTwoTeamsOfTwo"), text.getMessage("lblWebFactTeamLife", 30));
            default -> List.of();
        };
        // A variant the web has no wording for yet uses the engine's description
        return new Format(type.name(), type.toString(), FormatGroup.Variant,
                text.getMessageorUseDefault("lblWebDesc" + type.name(), type.getDescription()), facts,
                text.getMessageorUseDefault("lblWebPlay" + type.name(), ""), null, false);
    }

    /** Every entry of the lobby's Format menu, in FormatChoices' order: the game types and the legality formats together. */
    public static List<Format> choices() {
        final List<Format> out = new ArrayList<>();
        for (final Object choice : FormatChoices.get(true)) {
            if (choice instanceof GameType type) {
                out.add(explained(type));
            } else if (choice instanceof GameFormat format) {
                out.add(explained(format));
            }
        }
        return out;
    }

    /** A legality format in the same shape as a game type. It is played as Constructed, so its life and match text are Constructed's. */
    static Format explained(final GameFormat format) {
        final Localizer text = Localizer.getInstance();
        final GameFormat.DeckRules rules = format.getDeckRules();
        final int cards = rules.minMainDeckSize() > 0 ? rules.minMainDeckSize() : deckCards(GameType.Constructed);
        final List<String> facts = new ArrayList<>();
        facts.add(text.getMessage("lblWebFactDeckAtLeast", cards));
        if (rules.singleton()) {
            facts.add(text.getMessage("lblWebFactSingleton"));
        }
        if (format.getMaxPoints() > 0) {
            facts.add(text.getMessage("lblWebFactPoints", format.getMaxPoints()));
        }
        if (!format.getBannedCardNames().isEmpty()) {
            facts.add(text.getMessage("lblWebFactBanned", format.getBannedCardNames().size()));
        }
        if (!format.getRestrictedCards().isEmpty()) {
            facts.add(text.getMessage("lblWebFactRestricted", format.getRestrictedCards().size()));
        }
        facts.add(lifeFact(GameType.Constructed));
        return new Format(format.getName(), format.getName(), kind(format), lineOf(format), facts,
                text.getMessage("lblWebPlayConstructed"), cards, true);
    }

    /** FormatChoices lists no archived or digital formats, so every format it offers is one of these. */
    private static FormatGroup kind(final GameFormat format) {
        return switch (format.getFormatType()) {
            case SANCTIONED -> FormatGroup.Sanctioned;
            case CASUAL -> FormatGroup.Casual;
            default -> FormatGroup.Custom;
        };
    }

    /** Where a format's cards come from, in a few words. */
    private static String lineOf(final GameFormat f) {
        // Standard rotates, so its first set is not worth naming
        if (f.getFormatSubType() == GameFormat.FormatSubType.STANDARD) {
            return Localizer.getInstance().getMessage("lblWebLobbyRecentSets");
        }
        final List<CardRarity> rarities = f.getAllowedRarities();
        if (rarities != null && !rarities.isEmpty()
                && rarities.stream().noneMatch(r -> r == CardRarity.Uncommon || r == CardRarity.Rare || r == CardRarity.MythicRare)) {
            return Localizer.getInstance().getMessage("lblWebLobbyCommonsOnly");
        }
        CardEdition first = null;
        for (final String code : f.getAllowedSetCodes()) {
            final CardEdition e = StaticData.instance().getEditions().get(code);
            if (e != null && (first == null || e.getDate().before(first.getDate()))) {
                first = e;
            }
        }
        // A list that starts at Alpha counts as every set, even if it leaves out some later sets
        if (first == null || "LEA".equals(first.getCode())) {
            return Localizer.getInstance().getMessage(f.getRestrictedCards().isEmpty() ? "lblWebLobbyEverySet" : "lblWebLobbyEverySetRestricted");
        }
        return Localizer.getInstance().getMessage("lblWebLobbySetForward", first.getName());
    }

    private LobbyFormats() {
    }
}
